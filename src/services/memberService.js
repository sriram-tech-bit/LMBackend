'use strict';

const Member = require('../models/Member');
const BorrowRecord = require('../models/BorrowRecord');
const ApiError = require('../utils/ApiError');
const { parsePagination } = require('../utils/pagination');
const { resolveSort } = require('../validators/common');
const { MONGO_DUPLICATE_KEY_CODE } = require('../config/constants');

/**
 * Member operations: POST /api/members and the supporting reads/writes.
 */

/** Escape a user string before it goes into a RegExp. */
function escapeRegExp(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

/**
 * POST /api/members — register a new member.
 *
 * `membershipId` is generated by the schema when omitted, so the minimum
 * payload is `{ "name": "...", "email": "..." }`.
 *
 * @param {{name: string, email: string, membershipId?: string,
 *          joinedDate?: Date, phone?: string, status?: string}} payload
 * @returns {Promise<import('mongoose').Document>}
 */
async function createMember(payload) {
  try {
    return await Member.create(payload);
  } catch (error) {
    if (error && error.code === MONGO_DUPLICATE_KEY_CODE) {
      const field = Object.keys(error.keyPattern || {})[0] || 'field';
      const value = (error.keyValue || {})[field] ?? payload[field] ?? '';
      throw ApiError.conflict(`A member with this ${field} already exists`, {
        code: 'DUPLICATE_MEMBER',
        details: [{ field, message: `"${value}" is already registered`, code: 'duplicate' }],
      });
    }
    throw error;
  }
}

/**
 * GET /api/members — paginated list with an optional status filter and a
 * name / email / membershipId search.
 *
 * @param {{status?: string, search?: string, page?: string, limit?: string, sort?: string}} query
 */
async function listMembers(query = {}) {
  const { page, limit, skip } = parsePagination(query);

  const filter = {};
  if (query.status) filter.status = query.status;

  if (query.search) {
    const pattern = new RegExp(escapeRegExp(query.search), 'i');
    filter.$or = [{ name: pattern }, { email: pattern }, { membershipId: pattern }];
  }

  const [members, total] = await Promise.all([
    Member.find(filter)
      .sort(resolveSort(query.sort, { createdAt: -1 }))
      .skip(skip)
      .limit(limit)
      .lean({ virtuals: true }),
    Member.countDocuments(filter),
  ]);

  return { members, total, page, limit };
}

/**
 * GET /api/members/:id
 * @throws {ApiError} 404
 */
async function getMemberById(id) {
  const member = await Member.findById(id);
  if (!member) {
    throw ApiError.notFound(`No member found with id ${id}`, { code: 'MEMBER_NOT_FOUND' });
  }
  return member;
}

/**
 * PATCH /api/members/:id — update profile fields or suspend/reactivate.
 * @returns {Promise<import('mongoose').Document>}
 */
async function updateMember(id, payload) {
  const member = await Member.findById(id);
  if (!member) {
    throw ApiError.notFound(`No member found with id ${id}`, { code: 'MEMBER_NOT_FOUND' });
  }

  if (payload.name !== undefined) member.name = payload.name;
  if (payload.email !== undefined) member.email = payload.email;
  if (payload.phone !== undefined) member.phone = payload.phone;
  if (payload.status !== undefined) member.status = payload.status;

  try {
    await member.save();
  } catch (error) {
    if (error && error.code === MONGO_DUPLICATE_KEY_CODE) {
      const field = Object.keys(error.keyPattern || {})[0] || 'field';
      throw ApiError.conflict(`A member with this ${field} already exists`, {
        code: 'DUPLICATE_MEMBER',
      });
    }
    throw error;
  }

  return member;
}

/**
 * DELETE /api/members/:id — refused while the member still holds books, so a
 * borrow history never points at a missing member.
 */
async function deleteMember(id) {
  const member = await Member.findById(id);
  if (!member) {
    throw ApiError.notFound(`No member found with id ${id}`, { code: 'MEMBER_NOT_FOUND' });
  }

  const activeLoans = await BorrowRecord.countDocuments({ member: member._id, returnDate: null });
  if (activeLoans > 0) {
    throw ApiError.conflict(
      `Cannot delete ${member.membershipId}: ${activeLoans} book(s) are still on loan`,
      { code: 'MEMBER_HAS_ACTIVE_LOANS' }
    );
  }

  await member.deleteOne();
  return member;
}

module.exports = { createMember, listMembers, getMemberById, updateMember, deleteMember, escapeRegExp };
